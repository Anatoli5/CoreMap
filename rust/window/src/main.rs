thread_local! {
    static VIEW: RefCell<Option<Rc<RefCell<view::View>>>> = const { RefCell::new(None) };
}

/// Передаёт в поток окна то, что пришло из другого потока (канал, статистика), по порядку.
fn to_view(work: impl FnOnce(&mut view::View) + Send + 'static) {
    // Ошибка здесь значит, что цикл окна уже кончился (окно закрыто): показывать больше некому.
    let _ = slint::invoke_from_event_loop(move || {
        VIEW.with(|cell| {
            if let Some(view) = cell.borrow().as_ref() {
                work(&mut view.borrow_mut());
            }
        });
    });
}

/// Метка сборки (tools\rust.ps1): в окне не показывается, но остаётся в файле — пересобранный с новой меткой файл
/// другой, и Smart App Control судит его заново (без неё повторная сборка дала бы тот же файл и тот же отказ).
#[used]
static STAMP: &str = env!("COREMAP_BUILT");

/// Папка данных: `--data`, иначе data рядом с программой (её пишет программа входа; файл окна в ней пишет окно).
fn data_dir(args: &[String]) -> PathBuf {
    arg(args, "--data").map_or_else(
        || {
            std::env::current_exe()
                .ok()
                .and_then(|exe| exe.parent().map(|d| d.join("data")))
                .unwrap_or_else(|| PathBuf::from("data"))
        },
        PathBuf::from,
    )
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    // Пробный запуск после сборки (tools\rust.ps1): пустил ли Windows файл. Ничего не делает и выходит.
    if args.iter().any(|a| a == "--probe") {
        return;
    }
    if let Some(at) = args.iter().position(|a| a == "--conditional-report") {
        let (Some(input), Some(output)) = (args.get(at + 1), args.get(at + 2)) else {
            std::process::exit(2);
        };
        std::process::exit(conditional_report::run(
            PathBuf::from(input).as_path(),
            PathBuf::from(output).as_path(),
        ));
    }
    if let Some(at) = args.iter().position(|a| a == "--conditional-prepare") {
        let (Some(input), Some(output), Some(block)) = (args.get(at + 1), args.get(at + 2), args.get(at + 3)) else {
            std::process::exit(2);
        };
        std::process::exit(conditional_report::prepare(
            PathBuf::from(input).as_path(),
            PathBuf::from(output).as_path(),
            block,
        ));
    }
    if let Some(at) = args.iter().position(|a| a == "--model-report") {
        let (Some(dir), Some(out)) = (args.get(at + 1), args.get(at + 2)) else {
            std::process::exit(2);
        };
        std::process::exit(model_report::run(
            &PathBuf::from(dir),
            &PathBuf::from(out),
            arg(&args, "--split").as_deref(),
        ));
    }
    let pipe = arg(&args, "--pipe").unwrap_or_else(pipe::server_pipe);
    if let Some(snapshot) = arg(&args, "--snapshot") {
        let size = arg(&args, "--size")
            .and_then(|s| {
                s.split_once('x')
                    .and_then(|(w, h)| Some((w.parse().ok()?, h.parse().ok()?)))
            })
            .unwrap_or((1920, 1040));
        std::process::exit(check::run(
            pipe,
            &snapshot,
            size,
            arg(&args, "--data").map(PathBuf::from),
            if args.iter().any(|a| a == "--reopened") {
                check::Mode::Reopened
            } else if args.iter().any(|a| a == "--lost") {
                check::Mode::Lost
            } else if args.iter().any(|a| a == "--bye") {
                check::Mode::Bye
            } else if args.iter().any(|a| a == "--settings") {
                check::Mode::Settings
            } else {
                check::Mode::Full
            },
        ));
    }

    // Рисует процессор, и только изменившиеся участки: тем же способом окно проверено на картинках (src/check.rs).
    // Рисование видеокартой — открытый выбор, его решит замер (DECISIONS #28). Не выбрался — остаётся способ Slint
    // по умолчанию, который AppWindow::new возьмёт сам; окно от этого не теряется.
    let _ = slint::BackendSelector::new().renderer_name("software".into()).select();
    let ui = AppWindow::new().expect("окно");
    // Окно после сворачивания — целиком (обход ошибки Slint 1.18.1, src/restore.rs).
    restore::watch(&ui);
    // Номер версии (файл VERSION, tools\rust.ps1); метка сборки в заголовок не идёт — она только делает файл другим.
    ui.set_version(env!("COREMAP_VERSION").into());
    let data = data_dir(&args);
    // Размер и место из файла окна — до показа: окно сразу открывается там, где его оставили.
    let memory = saved::open(&ui, &data);
    // События канала приходят в его потоке и передаются в поток окна по порядку.
    let link = pipe::Link::start(pipe, |event| to_view(move |view| view.on_event(event)));
    let view = Rc::new(RefCell::new(view::View::new(&ui, link, memory)));
    VIEW.with(|cell| *cell.borrow_mut() = Some(Rc::clone(&view)));
    connect(&ui, &view);
    // Поток статистики живёт, пока жив его отправитель, — до конца окна; окно шлёт ему блоки и соседей для модели.
    let stats = store::start(data, |delivery| {
        to_view(move |view| match delivery {
            store::Delivery::Digest(digest) => view.on_digest(digest),
            store::Delivery::Day(day) => view.on_day(day),
        });
    });
    view.borrow_mut().stats_to(stats);
    ui.run().expect("окно");
}
