// Окно: кнопка «новое окно» — открыть окно на Rust (CoreMapWindow.exe) вместо этого (DECISIONS #29, #30).
// Два Core разом недопустимы (шапка Engine.cs), поэтому это окно закрывается, а новое открывает движок, когда
// процесс этого кончился. Движок работает, пока открыто новое окно или идёт измерение, и потом выходит сам.
// Кнопка временная: уйдёт вместе с этим окном, когда в новое переедут все разделы.
namespace CoreMap
{
    partial class MainForm
    {
        void NewWindowControls(System.Windows.Forms.Control bar)
        {
            bar.Controls.Add(Widgets.Button("новое окно", NewWindowClick,
                "Новое окно\nОткрывает новое окно программы, а это закрывает: с процессором оба сразу работать не могут.\n" +
                "• в новом окне пока только «Кристалл», остальное — здесь\n" +
                "• вернуться сюда: закрыть новое окно и открыть CoreMap ярлыком, как обычно\n" +
                "• во время измерения не срабатывает: сначала дождись его конца или останови"));
        }

        void NewWindowClick()
        {
            if (core.Busy)
            {
                Report("идёт измерение — новое окно откроется после него: дождись конца или останови");
                return;
            }
            string refusal = Tray.RequestNewWindow(core.Simulated);
            if (refusal != null)
            {
                Report("новое окно не открыто: " + refusal);
                return;
            }
            Close();
        }
    }
}
